import * as ddb from "@aws-sdk/client-dynamodb";
import {marshall} from "@aws-sdk/util-dynamodb";
import {
    ExpressionGenerator,
    TableSchema, TableKey,
    TableType,
    UpdateContext,
    updateExpression,
    UpdateGenerator
} from "./schema";
import {MarshalOptions, prepareCommand} from "./util";
import _ from "lodash";

/**
 * DynamoDb {@link ddb.UpdateItemCommandInput} for a given {@link TableSchema}
 */
export interface UpdateCommand<T extends TableSchema, V> {
    /**
     * See {@link ddb.UpdateItemInput.Key}
     */
    key: TableKey<T>,
    /**
     * Context values to be used in expressions generated by {@link expression} or {@link condition}.
     */
    values?: V,
    /**
     * Function generating {@link ddb.UpdateItemInput.UpdateExpression}
     */
    expression?: UpdateGenerator<T, TableKey<T> & V>
    /**
     * Function generating {@link ddb.UpdateItemInput.ConditionExpression}
     */
    condition?: ExpressionGenerator<T, TableKey<T> & V>
    /**
     * See {@link ddb.UpdateItemInput.ReturnValues}
     */
    return?: ddb.ReturnValue
    /**
     * See {@link ddb.UpdateItemInput.ReturnValuesOnConditionCheckFailure}
     */
    returnOnConditionFailure?: ddb.ReturnValuesOnConditionCheckFailure
    /**
     * See {@link ddb.UpdateItemInput.ReturnConsumedCapacity}
     */
    returnConsumedCapacity?: ddb.ReturnConsumedCapacity
    /**
     * See {@link ddb.UpdateItemInput.ReturnItemCollectionMetrics}
     */
    returnCollectionMetrics?: ddb.ReturnItemCollectionMetrics
}

/**
 * Create {@link ddb.UpdateItemCommandInput}
 * @param tbl - target table
 * @param command - command parameters
 */
export function update<T extends TableType<T>, V>(tbl: T, command: UpdateCommand<T, V>): ddb.UpdateItemCommandInput {
    const dynamoKey = marshall(command.key, MarshalOptions)
    const context = {...command.values, ...command.key} as TableKey<T> & V
    const {
        attributeNames,
        attributeValues,
        key,
        attr,
        ref
    } = prepareCommand(tbl, context, dynamoKey);
    const {expression, condition} = command
    const update = expression?.(new UpdateContext(ref, key, attr))

    /**
     * set: {
     *     [attr.visit_count]: `if_not_exists(${attr.visit_count}, ${val.start}<--undefined here!!!)`
     * }
     */
    return {
        TableName: tbl.name,
        Key: dynamoKey,
        UpdateExpression: update !== undefined ? updateExpression(update) : undefined,
        ConditionExpression: condition?.({key, attr, ref: ref}) ?? undefined,
        ExpressionAttributeValues: !_.isEmpty(attributeValues) ? attributeValues : undefined,
        ExpressionAttributeNames: !_.isEmpty(attributeNames) ? attributeNames : undefined,
        ReturnValuesOnConditionCheckFailure: command.returnOnConditionFailure,
        ReturnValues: command.return,
        ReturnConsumedCapacity: command.returnConsumedCapacity,
        ReturnItemCollectionMetrics: command.returnCollectionMetrics,
    };
}

/**
 * Create {@link ddb.UpdateItemCommand}.
 * @param tbl - target table
 * @param command - command parameters
 */
export function updateCommand<T extends TableType<T>, V>(tbl: T, command: UpdateCommand<T, V>): ddb.UpdateItemCommand {
    return new ddb.UpdateItemCommand(update(tbl, command))
}
