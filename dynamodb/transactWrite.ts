import * as ddb from "@aws-sdk/client-dynamodb";
import {marshall} from "@aws-sdk/util-dynamodb";
import {KeySchema, TableType, SchemaType, ExpressionGenerator, AttributesSchema, TableSchema} from "./schema";
import {prepareCommand} from "./util";
import _ from "lodash";

/**
 * Defines {@link ddb.TransactWriteItem} for a {@link ddb.TransactWriteItemsCommand}
 */
type TransactWriteItem<T, V> =
    TransactPutItem<T, V>
    | TransactUpdateItem<T, V>
    | TransactDeleteItem<T, V>
    | TransactCheckItem<T, V>

/**
 * Request to put an item into the table (see {@link ddb.Put}).
 */
interface TransactPutItem<T, V> {
    /**
     * Indicate put request.
     */
    action: "put",
    /**
     * Table item key.
     */
    key: SchemaType<KeySchema<T>>
    /**
     * Non-key attributes.
     */
    item?: Partial<SchemaType<AttributesSchema<T>>>,
    /**
     * Context values to be used in expressions generated by {@link condition}.
     */
    values?: V
    /**
     * Function generating {@link ddb.Put.ConditionExpression}
     */
    condition?: ExpressionGenerator<T, SchemaType<TableSchema<T>> & V>
    /**
     * See {@link ddb.Put.ReturnValuesOnConditionCheckFailure}
     */
    returnOnConditionFailure?: ddb.ReturnValuesOnConditionCheckFailure
}

/**
 * Request to put an item into the table (see {@link ddb.Update}).
 */
interface TransactUpdateItem<T, V> {
    /**
     * Indicate put request.
     */
    action: "update",
    /**
     * Table item key.
     */
    key: SchemaType<KeySchema<T>>
    /**
     * Context values to be used in expressions generated by {@link expression} or {@link condition}.
     */
    values?: V,
    /**
     * Function generating {@link ddb.Update.UpdateExpression}
     */
    expression: ExpressionGenerator<T, SchemaType<KeySchema<T>> & V>
    /**
     * Function generating {@link ddb.Update.ConditionExpression}
     */
    condition?: ExpressionGenerator<T, SchemaType<KeySchema<T>> & V>
    /**
     * See {@link ddb.Update.ReturnValuesOnConditionCheckFailure}
     */
    returnOnConditionFailure?: ddb.ReturnValuesOnConditionCheckFailure
}

/**
 * Request to delete an item from the table (see {@link ddb.Delete}).
 */
interface TransactDeleteItem<T, V> {
    /**
     * Indicate delete request.
     */
    action: "delete",
    /**
     * Table item key.
     */
    key: SchemaType<KeySchema<T>>
    /**
     * Context values to be used in expressions generated by {@link condition}.
     */
    values?: V,
    /**
     * Function generating {@link ddb.Delete.ConditionExpression}
     */
    condition?: ExpressionGenerator<T, SchemaType<KeySchema<T>> & V>
    /**
     * See {@link ddb.Delete.ReturnValuesOnConditionCheckFailure}
     */
    returnOnConditionFailure?: ddb.ReturnValuesOnConditionCheckFailure
}

/**
 * Request to put an item into the table (see {@link ddb.ConditionCheck}).
 */
interface TransactCheckItem<T, V> {
    /**
     * Indicate put request.
     */
    action: "check",
    /**
     * Table item key.
     */
    key: SchemaType<KeySchema<T>>
    /**
     * Context values to be used in expressions generated by {@link condition}.
     */
    values?: V,
    /**
     * Function generating {@link ddb.ConditionCheck.ConditionExpression}
     */
    condition: ExpressionGenerator<T, SchemaType<KeySchema<T>> & V>
    /**
     * See {@link ddb.ConditionCheck.ReturnValuesOnConditionCheckFailure}
     */
    returnOnConditionFailure?: ddb.ReturnValuesOnConditionCheckFailure
}

/**
 * Builds batch write operation.
 */
interface TransactWriteBuilder {
    /**
     * Add batch of items to {@link ddb.TransactWriteItemsCommandInput}.
     * @param tbl - target table
     * @param txItem - transaction item
     */
    add<Table extends TableType<Table>, V>(tbl: Table, txItem: TransactWriteItem<Table, V>): TransactWriteBuilder

    /**
     * See {@link ddb.TransactWriteItemsInput.ReturnConsumedCapacity}
     * @param capacity - consumed capacity setting
     */
    returnConsumedCapacity(capacity: ddb.ReturnConsumedCapacity): TransactWriteBuilder

    /**
     * See {@link ddb.TransactWriteItemsInput.ReturnItemCollectionMetrics}
     * @param metrics - item collection metric setting
     */
    returnItemCollectionMetrics(metrics: ddb.ReturnItemCollectionMetrics): TransactWriteBuilder

    /**
     * See {@link ddb.TransactWriteItemsInput.ClientRequestToken}
     * @param token - idempotency token
     */
    clientRequestToken(token: string): TransactWriteBuilder

    /**
     * Build {@link ddb.TransactWriteItemsCommandInput}
     */
    input(): ddb.TransactWriteItemsCommandInput

    /**
     * Build {@link ddb.TransactWriteItemsCommand}
     */
    command(): ddb.TransactWriteItemsCommand
}

/**
 * Create a builder for {@link ddb.TransactWriteItemsCommandInput} and {@link ddb.TransactWriteItemsCommand}
 */
export function transactWrite(): TransactWriteBuilder {
    let items: ddb.TransactWriteItem[] = [];
    let returnConsumedCapacity: ddb.ReturnConsumedCapacity | undefined;
    let returnItemCollectionMetrics: ddb.ReturnItemCollectionMetrics | undefined;
    let clientRequestToken: string | undefined

    return {
        add<Table extends TableType<Table>, V>(tbl: Table, txItem: TransactWriteItem<Table, V>) {
            switch (txItem.action) {
                case "put": {
                    const dynamoItem = marshall({...txItem.item, ...txItem.key})
                    const context = {...txItem.values, ...txItem.item, ...txItem.key} as SchemaType<TableSchema<Table>> & V;
                    const {
                        attributeNames,
                        attributeValues,
                        key,
                        attr,
                        val
                    } = prepareCommand(tbl, context, dynamoItem);
                    const {condition} = txItem

                    items.push({
                        Put: {
                            TableName: tbl.name,
                            Item: dynamoItem,
                            ConditionExpression: condition?.({key, attr, val}),
                            ReturnValuesOnConditionCheckFailure: txItem.returnOnConditionFailure,
                            ExpressionAttributeNames: !_.isEmpty(attributeNames) ? attributeNames : undefined,
                            ExpressionAttributeValues: !_.isEmpty(attributeValues) ? attributeValues : undefined,
                        }
                    })
                    break;
                }
                case "update": {
                    const dynamoKey = marshall(txItem.key)
                    const context = {...txItem.values, ...txItem.key} as SchemaType<KeySchema<Table>> & V;
                    const {
                        attributeNames,
                        attributeValues,
                        key,
                        attr,
                        val
                    } = prepareCommand(tbl, context, dynamoKey);
                    const {expression, condition} = txItem

                    items.push({
                        Update: {
                            TableName: tbl.name,
                            Key: dynamoKey,
                            UpdateExpression: expression?.({key, attr, val}),
                            ConditionExpression: condition?.({key, attr, val}),
                            ReturnValuesOnConditionCheckFailure: txItem.returnOnConditionFailure,
                            ExpressionAttributeNames: !_.isEmpty(attributeNames) ? attributeNames : undefined,
                            ExpressionAttributeValues: !_.isEmpty(attributeValues) ? attributeValues : undefined,
                        }
                    })
                    break;
                }
                case "delete": {
                    const context = {...txItem.values, ...txItem.key} as SchemaType<KeySchema<Table>> & V;
                    const dynamoKey = marshall(txItem.key)
                    const {
                        attributeNames,
                        attributeValues,
                        key,
                        attr,
                        val
                    } = prepareCommand(tbl, context, dynamoKey);
                    const {condition} = txItem

                    items.push({
                        Delete: {
                            TableName: tbl.name,
                            Key: dynamoKey,
                            ConditionExpression: condition?.({key, attr, val}),
                            ReturnValuesOnConditionCheckFailure: txItem.returnOnConditionFailure,
                            ExpressionAttributeNames: !_.isEmpty(attributeNames) ? attributeNames : undefined,
                            ExpressionAttributeValues: !_.isEmpty(attributeValues) ? attributeValues : undefined,
                        }
                    })
                    break;
                }
                case "check": {
                    const context = {...txItem.values, ...txItem.key} as SchemaType<TableSchema<Table>> & V;
                    const dynamoKey = marshall(txItem.key)
                    const {
                        attributeNames,
                        attributeValues,
                        key,
                        attr,
                        val
                    } = prepareCommand(tbl, context, dynamoKey);
                    const {condition} = txItem

                    items.push({
                        ConditionCheck: {
                            TableName: tbl.name,
                            Key: dynamoKey,
                            ConditionExpression: condition?.({key, attr, val}),
                            ReturnValuesOnConditionCheckFailure: txItem.returnOnConditionFailure,
                            ExpressionAttributeNames: !_.isEmpty(attributeNames) ? attributeNames : undefined,
                            ExpressionAttributeValues: !_.isEmpty(attributeValues) ? attributeValues : undefined,
                        }
                    })
                    break;
                }
            }

            return this
        },
        returnConsumedCapacity(capacity: ddb.ReturnConsumedCapacity) {
            returnConsumedCapacity = capacity
            return this
        },
        returnItemCollectionMetrics(metrics: ddb.ReturnItemCollectionMetrics) {
            returnItemCollectionMetrics = metrics
            return this
        },
        clientRequestToken(token: string) {
            clientRequestToken = token
            return this
        },
        input() {
            return {
                TransactItems: items,
                ClientRequestToken: clientRequestToken,
                ReturnConsumedCapacity: returnConsumedCapacity,
                ReturnItemCollectionMetrics: returnItemCollectionMetrics
            }
        },
        command() {
            return new ddb.TransactWriteItemsCommand(this.input())
        }
    }
}

