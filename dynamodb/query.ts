import * as ddb from "@aws-sdk/client-dynamodb";
import {marshall} from "@aws-sdk/util-dynamodb";
import {
    TableType,
    Schema,
    ExpressionGenerator,
    FilterConditionGenerator,
    KeyConditionGenerator, TableSchema, TableKey
} from "./schema";
import {MarshalOptions, prepareCommand} from "./util";
import _ from "lodash";

/**
 * DynamoDb {@link ddb.QueryCommandInput} for a given {@link TableSchema}
 */
interface QueryCommand<T extends TableSchema, V> {
    /**
     * See {@link ddb.QueryInput.IndexName}
     */
    indexName?: string
    /**
     * Context values to be used in expressions generated by {@link keyCondition} or {@link filter}.
     */
    values?: V
    /**
     * Function generating {@link ddb.QueryInput.KeyConditionExpression}
     */
    keyCondition?: KeyConditionGenerator<T, V>
    /**
     * Function generating {@link ddb.QueryInput.FilterExpression}
     */
    filter?: FilterConditionGenerator<T, V>
    /**
     * Function generating {@link ddb.QueryInput.ProjectionExpression}
     */
    projection?: ExpressionGenerator<T, never>
    /**
     * See {@link ddb.QueryInput.Select}
     */
    select?: ddb.Select
    /**
     * See {@link ddb.QueryInput.Limit}
     */
    limit?: number
    /**
     * See {@link ddb.QueryInput.ScanIndexForward}
     */
    scanIndexForward?: boolean
    /**
     * See {@link ddb.QueryInput.ExclusiveStartKey}
     */
    exclusiveStartKey?: TableKey<T>,
    /**
     * See {@link ddb.QueryInput.ConsistentRead}
     */
    consistentRead?: boolean
    /**
     * See {@link ddb.QueryInput.ReturnConsumedCapacity}
     */
    returnConsumedCapacity?: ddb.ReturnConsumedCapacity
}

/**
 * Create {@link ddb.QueryCommandInput}.
 * @param tbl - target table
 * @param command - command parameters
 */
export function query<T extends TableType<T>, V>(tbl: T, command: QueryCommand<T, V>): ddb.QueryCommandInput {
    const context = command.values
    const {
        attributeNames,
        attributeValues,
        key,
        attr,
        val
    } = prepareCommand(tbl, context as NonNullable<V>)
    const {keyCondition, filter, projection} = command

    let filterExpression = filter?.({attr, val});
    if (filterExpression?.trim() === '') filterExpression = undefined
    return {
        TableName: tbl.name,
        IndexName: command.indexName,
        KeyConditionExpression: keyCondition?.({key, val}),
        ProjectionExpression: projection?.({key, attr, val}),
        FilterExpression: filterExpression,
        Select: command.select,
        Limit: command.limit,
        ExclusiveStartKey: command.exclusiveStartKey !== undefined ? marshall(command.exclusiveStartKey, MarshalOptions) : undefined,
        ScanIndexForward: command.scanIndexForward,
        ConsistentRead: command.consistentRead,
        ReturnConsumedCapacity: command.returnConsumedCapacity,
        ExpressionAttributeNames: !_.isEmpty(attributeNames) ? attributeNames : undefined,
        ExpressionAttributeValues: !_.isEmpty(attributeValues) ? attributeValues : undefined,
    };
}

/**
 * Create {@link ddb.QueryCommand}.
 * @param tbl - target table
 * @param command - command parameters
 */
export function queryCommand<T extends TableType<T>, V>(tbl: T, command: QueryCommand<T, V>): ddb.QueryCommand {
    return new ddb.QueryCommand(query(tbl, command))
}