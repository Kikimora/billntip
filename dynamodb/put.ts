import * as ddb from "@aws-sdk/client-dynamodb";
import {marshall} from "@aws-sdk/util-dynamodb";
import {TableType, ExpressionGenerator, TableKey, TableSchema, TableAttributes} from "./schema";
import {MarshalOptions, prepareCommand} from "./util";
import _ from "lodash";

/**
 * DynamoDb {@link ddb.PutItemCommandInput} for a given {@link TableSchema}
 */
interface PutCommand<T extends TableSchema, V> {
    /**
     * A key portion of the {@link ddb.PutItemInput.Item}
     */
    key: TableKey<T>,
    /**
     * A non-key portion of the {@link ddb.PutItemInput.Item}
     */
    item: TableAttributes<T>,
    /**
     * Context values to be used in expressions generated by {@link condition}.
     */
    values?: V
    /**
     * Function generating {@link ddb.PutItemInput.ConditionExpression}
     */
    condition?: ExpressionGenerator<T, TableKey<T> & V>
    /**
     * See {@link ddb.PutItemInput.ReturnValues}
     */
    return?: ddb.ReturnValue
    /**
     * See {@link ddb.PutItemInput.ReturnValuesOnConditionCheckFailure}
     */
    returnOnConditionFailure?: ddb.ReturnValuesOnConditionCheckFailure
    /**
     * See {@link ddb.PutItemInput.ReturnConsumedCapacity}
     */
    returnConsumedCapacity?: ddb.ReturnConsumedCapacity
    /**
     * See {@link ddb.PutItemInput.ReturnItemCollectionMetrics}
     */
    returnCollectionMetrics?: ddb.ReturnItemCollectionMetrics
}

/**
 * Create {@link ddb.PutItemCommandInput}.
 * @param tbl - target table
 * @param command - command parameters
 */
export function put<T extends TableType<T>, V>(tbl: T, command: PutCommand<T, V>): ddb.PutItemCommandInput {
    const dynamoItem = marshall({...command.item, ...command.key}, MarshalOptions)
    const context = {...command.values, ...command.item, ...command.key} as TableKey<T> & V;
    const {
        attributeNames,
        attributeValues,
        key,
        attr,
        val
    } = prepareCommand(tbl, context, dynamoItem);
    const {condition} = command

    return {
        TableName: tbl.name,
        Item: dynamoItem,
        ConditionExpression: condition?.({key, attr, val}) ?? undefined,
        ExpressionAttributeValues: !_.isEmpty(attributeValues) ? attributeValues : undefined,
        ExpressionAttributeNames: !_.isEmpty(attributeNames) ? attributeNames : undefined,
        ReturnValues: command.return,
        ReturnValuesOnConditionCheckFailure: command.returnOnConditionFailure,
        ReturnConsumedCapacity: command.returnConsumedCapacity,
        ReturnItemCollectionMetrics: command.returnCollectionMetrics
    };
}

/**
 * Create {@link ddb.PutItemCommand}.
 * @param tbl - target table
 * @param command - command parameters
 */
export function putCommand<T extends TableType<T>, V>(tbl: T, command: PutCommand<T, V>): ddb.PutItemCommand {
    return new ddb.PutItemCommand(put(tbl, command))
}
